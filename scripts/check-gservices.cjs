/**
 * Firebase push guard.
 *
 * React Native Firebase reads the resources the google-services gradle plugin
 * generates from `android/app/google-services.json`. Every failure mode below
 * is silent at app runtime (the token simply never registers), so this check
 * makes them loud instead:
 *
 *   - no file at all          → FCM push stays off by design (build green)
 *   - a BOM from an editor    → google's parser tolerates it, but strip anyway
 *   - package mismatch        → plugin picks nothing; token registration fails
 *   - missing api key/number  → FirebaseApp cannot initialize
 *
 * Usage: node scripts/check-gservices.cjs
 * Always exits 0 unless something is actively broken — push-off is a fact, not
 * an error.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const jsonPath = path.join(root, 'android', 'app', 'google-services.json');
const gradlePath = path.join(root, 'android', 'app', 'build.gradle');

if (!fs.existsSync(jsonPath)) {
  console.log('No android/app/google-services.json - FCM push stays off (expected until configured).');
  process.exit(0);
}

let problems = [];
let notes = [];

// 1. A BOM at the start is what PowerShell text writes leave behind.
const raw = fs.readFileSync(jsonPath);
const head = raw.subarray(0, 3).toString('hex');
if (head === 'ef bb bf') {
  notes.push('file starts with a UTF-8 BOM; google-services tolerates it, but stripping is safer');
}

let cfg;
try {
  cfg = JSON.parse(raw.toString('utf8').replace(/^\uFEFF/, ''));
} catch (caught) {
  console.error(`google-services.json is not valid JSON: ${caught.message}`);
  process.exit(1);
}

const appId = 'com.stargazer.veill';
try {
  const gradle = fs.readFileSync(gradlePath, 'utf8');
  const match = gradle.match(/applicationId\s+['"]([^'"]+)['"]/);
  if (match) {
    // The read package always wins; the constant above is only its default.
    // eslint-disable-next-line no-unused-vars
    const declared = match[1];
    problems.push(declared === appId ? null : `build.gradle applicationId is ${declared}`);
  }
} catch {
  notes.push('could not read applicationId from android/app/build.gradle; assumed com.stargazer.veill');
}

// 2. The plugin matches the app by package; a wrong pick means JSON that does
//    not correspond to this app was dropped in.
const clients = (cfg.client || []).map(
  (client) => client?.client_info?.android_client_info?.package_name || '(no package)'
);
const matching = clients.filter((name) => name === appId);
if (matching.length === 0) {
  problems.push(
    `no client with package ${appId} (file contains: ${clients.join(', ') || 'nothing'}) - ` +
      'add this Android package in the Firebase console and re-download'
  );
}

// 3. The pieces FirebaseApp.initializeApp needs.
if (!cfg.project_info?.project_number) problems.push('project_info.project_number missing');
if (!cfg.project_info?.project_id) problems.push('project_info.project_id missing');
const apiKeyCount = (cfg.client || []).reduce(
  (sum, client) => sum + (client.api_key?.[0]?.current_key ? 1 : 0),
  0
);
if (matching.length > 0 && apiKeyCount === 0) {
  problems.push('no api_key present for the matching client');
}

if (problems.filter(Boolean).length) {
  console.error('google-services.json problems:');
  for (const problem of problems.filter(Boolean)) console.error(' - ' + problem);
  process.exit(1);
}

for (const note of notes) console.log('note: ' + note);
console.log(
  `google-services.json OK: project ${cfg.project_info.project_id} ` +
    `(client ${appId}); FCM push will be generated by the gradle plugin on build.`
);
